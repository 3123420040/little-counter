type FactorInput = Omit<
  DashboardMetricRegistryFactorV1,
  | "activationStatus"
  | "currentVisible"
  | "legacyFallback"
  | "reportAsOfRequired"
  | "unavailableTargetMetricIds"
> & { unavailableTargetMetricIds?: string[] };

function factor(input: FactorInput): DashboardMetricRegistryFactorV1 {
  return {
    ...input,
    targetMetricIds: [...input.targetMetricIds].sort(),
    unavailableTargetMetricIds: [...(input.unavailableTargetMetricIds ?? [])].sort(),
    targetSources: [...input.targetSources].sort(),
    timeBasis: [...input.timeBasis].sort(),
    activationDependencies: [...input.activationDependencies].sort(),
    currentVisible: true,
    reportAsOfRequired: true,
    activationStatus: "inactive",
    legacyFallback: "forbidden",
  };
}

