function freezeRegistry(input: DashboardMetricRegistryV1): DashboardMetricRegistryV1 {
  for (const entry of input.factors) {
    Object.freeze(entry.currentLabelsVi);
    Object.freeze(entry.targetMetricIds);
    Object.freeze(entry.unavailableTargetMetricIds);
    Object.freeze(entry.targetSources);
    Object.freeze(entry.timeBasis);
    Object.freeze(entry.activationDependencies);
    Object.freeze(entry);
  }
  Object.freeze(input.factors);
  return Object.freeze(input);
}

